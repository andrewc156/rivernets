def parse_rivers(html):
    """Pull label / bounds / pixel rows (P) / segments (S) for each river out of the JS."""
    start = html.index("var RIVERS = ")
    end = html.index("var MINZ", start)
    block = html[start:end]
    decoder = json.JSONDecoder()

    def value_after(field, pos):
        i = block.index(f"{field}: ", pos) + len(field) + 2
        value, j = decoder.raw_decode(block, i)
        return value, j

    rivers = {}
    for m in re.finditer(r'"(\w+)": \{\s*label: ', block):
        pos = m.start()
        label, pos = value_after("label", pos)
        bounds, pos = value_after("bounds", pos)
        pixels, pos = value_after("P", pos)
        segments, pos = value_after("S", pos)
        rivers[m.group(1)] = {"label": label, "bounds": bounds, "P": pixels, "S": segments}
    return rivers


