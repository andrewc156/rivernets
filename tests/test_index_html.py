@pytest.mark.browser
@pytest.mark.parametrize("river", RIVERS)
@pytest.mark.parametrize("view", VIEWS)
def test_switches(site, graphs, river, view):
    site.open()
    site.click(f"button[data-river={river}]")
    site.click(f"button[data-view={view}]")
    s = site.state()

    gc, gu = graphs[river]
    graph = gc if view == "compressed" else gu
    assert s["hash"] == f"#{river}/{view}"
    assert s["active"] == [RIVERS[river]["label"], view.capitalize()]
    assert f"{graph.number_of_nodes():,}" in s["stats"]
    assert s["legend"] == f"({RIVERS[river]['label']} · {view})"

    overlays = " | ".join(s["overlays"])
    assert "Water-quality stations" in overlays
    if view == "compressed":
        assert "Compressed nodes" in overlays and "River-pixel nodes" not in overlays
    else:
        assert "River-pixel nodes" in overlays and "Compressed nodes" not in overlays

    # only the active river's WQ markers are on the map
    wq_markers = site.page.eval_on_selector_all(".awesome-marker-icon-blue", "e => e.length")
    assert wq_markers == len(wq_station_nodes(gc))


@pytest.mark.browser
@pytest.mark.parametrize("river", RIVERS)
def test_pixels_draw_when_zoomed_in_and_have_popups(site, site_rivers, river):
    site.open(f"#{river}/uncompressed")
    assert "Zoom in" in site.state()["note"]

    pixels = site_rivers[river]["P"]
    p = pixels[len(pixels) // 2]
    site.set_view(p[LAT], p[LON], 13)
    note = site.state()["note"]
    assert "river-pixel nodes in view" in note
    assert int(re.sub(r"\D", "", note.split(" ")[0]) or 0) > 0

    # click the drawn pixel closest to the centre and read its popup
    xy = site.page.evaluate(f"""(() => {{
        const m = {site.map}, c = m.getCenter(); let best = null;
        m.eachLayer(l => {{
            if (l instanceof L.CircleMarker && l._i !== undefined) {{
                const d = l.getLatLng().distanceTo(c);
                if (!best || d < best[0]) best = [d, l];
            }}
        }});
        const q = m.latLngToContainerPoint(best[1].getLatLng());
        return [q.x, q.y];
    }})()""")
    site.page.mouse.click(*xy)
    popup = site.page.wait_for_selector(".leaflet-popup-content").inner_text()
    assert "River-pixel node" in popup
    assert RIVERS[river]["label"] in popup
    assert "Distance to outlet" in popup


