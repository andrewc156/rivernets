def test_site_size_reasonable():
    size_mb = SITE.stat().st_size / 1e6
    assert size_mb < MAX_SITE_MB, f"index.html is {size_mb:.1f} MB"


def test_all_rivers_present(site_rivers):
    assert set(site_rivers) == set(RIVERS)
    for key, r in site_rivers.items():
        assert r["label"] == RIVERS[key]["label"]


@pytest.mark.parametrize("river", RIVERS)
def test_pixels_match_uncompressed_graph(site_rivers, graphs, river):
    _, gu = graphs[river]
    pixels = site_rivers[river]["P"]
    assert len(pixels) == gu.number_of_nodes()
    assert {p[NODE] for p in pixels} == set(gu.nodes)


@pytest.mark.parametrize("river", RIVERS)
def test_segments_match_compressed_graph(site_rivers, graphs, river):
    gc, gu = graphs[river]
    segments = site_rivers[river]["S"]
    assert len(segments) == gc.number_of_edges()
    assert {(u, v) for u, v, *_ in segments} == set(gc.edges)
    # every pixel edge is accounted for by exactly one compressed edge
    assert sum(s[2] for s in segments) == gu.number_of_edges()


@pytest.mark.parametrize("river", RIVERS)
def test_every_pixel_is_on_an_edge_or_kept(site_rivers, graphs, river):
    gc, _ = graphs[river]
    pixels = site_rivers[river]["P"]
    n_segments = len(site_rivers[river]["S"])
    kept = {p[NODE] for p in pixels if p[SEG] == -1}
    assert kept == set(gc.nodes), "pixels marked as 'kept' should be exactly the compressed nodes"
    assert all(-1 <= p[SEG] < n_segments for p in pixels)


@pytest.mark.parametrize("river", RIVERS)
def test_pixel_values_sane(site_rivers, river):
    r = site_rivers[river]
    (lat0, lon0), (lat1, lon1) = r["bounds"]
    pixels = r["P"]
    eps = 1e-5  # pixel coordinates are rounded to 5 decimals, bounds are not
    assert all(lat0 - eps <= p[LAT] <= lat1 + eps and lon0 - eps <= p[LON] <= lon1 + eps for p in pixels)
    assert all(p[DIST] >= 0 and p[UP] >= 0 for p in pixels)
    outlets = [p for p in pixels if p[DIST] == 0]
    assert len(outlets) >= 1
    # the outlet drains everything else
    assert max(p[UP] for p in pixels) == len(pixels) - 1


def test_one_wq_marker_per_station_node(html, graphs):
    expected = sum(len(wq_station_nodes(gc)) for gc, _ in graphs.values())
    flask_markers = len(re.findall(r'"icon":\s*"flask"', html))
    assert flask_markers == expected


def test_no_train_test_labels(html):
    """Evaluation is leave-one-out, so the map must not label stations train/test."""
    for text in ["Training — 5/5", "held-out", "PARTIAL TEST", "FULL TEST", "TRAIN:"]:
        assert text not in html, f"found stale label {text!r}"


def test_toggle_script_wired_up(html):
    # each placeholder in the notebook's JS template must have been replaced
    assert not re.search(r"__[A-Z_]+__", html), "unreplaced __PLACEHOLDER__ in the page JS"
    search_vars = set(re.findall(r"var (\w+searchControl) = new L.Control.Search", html))
    assert search_vars, "search control missing"
    hooked = set(re.findall(r"(\w+searchControl)\.on\(\"search:locationfound\"", html))
    assert hooked and hooked <= search_vars, "river-switch search hook points at a missing variable"


